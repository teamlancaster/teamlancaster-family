// Builds src/public-facts.js from D1. This is the ONLY way public names get into the bundle.
// The public guide and public search import that file; they never query D1.
//
//   node scripts/build-public-facts.js            # local dev D1 (default)
//   node scripts/build-public-facts.js --remote   # production D1 (deploy only)
//
// Reads people with public_ok = 1 (the "public name" flag) and checks adult_confirmed
// (the "confirmed adult" flag). Writes first names and roles only. Refuses to write
// anything if a selected person is not a confirmed adult, counts as a minor, or if a
// row carries any field beyond the first name and the role (a surname, a year, an id).
import { execFileSync } from 'node:child_process';
import { writeFileSync, renameSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { isMinor } from '../src/lib/privacy.js';

export class FactsError extends Error {}

// How-to text is static. It is not read from D1 and it never names a person.
export const HOW_TO = [
  'This is a private, family-only site. Nothing here is indexed by search engines or archived.',
  'The front page shows the family crest and the first names of the founders and branch parents.',
  'Each branch has its own private area. To open yours, click "Family members: open your branch" and enter the passphrase your branch shared with you.',
  'If you do not have your branch passphrase, ask a family member in your branch. The guide cannot share passphrases.',
  'To fix or add something, use "Request a change" at the bottom of the page. Describe who it is about and what should change. A family admin reviews every request before anything changes.',
  'Inside a branch you will find that branch\'s tree, stories and photos, plus "Ask the tree" for questions about that branch.',
];

const CHECK_COLUMNS = ['role', 'first_name', 'adult_confirmed', 'public_ok', 'hidden', 'birth_year', 'death_year', 'is_deceased', 'branch_id', 'ord'];

/**
 * Turn raw D1 rows into {founders, branchParents}, or throw FactsError and write nothing.
 * A row is only eligible when public_ok = 1. Every eligible row must be a confirmed adult
 * and not a minor, and must not carry anything beyond the first name and the role.
 */
export function projectPublicFacts(rawRows) {
  for (const row of rawRows) {
    for (const k of Object.keys(row)) {
      if (!CHECK_COLUMNS.includes(k)) throw new FactsError(`Refusing to write: row has a field beyond first name and role (${k}).`);
    }
  }
  const chosen = [];
  const founders = rawRows.filter((r) => r.role === 'founder' && r.public_ok);
  for (const r of founders.slice(0, 2)) chosen.push(r);
  const seen = new Set();
  for (const r of rawRows.filter((r) => r.role === 'branch' && r.public_ok && !r.hidden)) {
    if (seen.has(r.branch_id)) continue;
    seen.add(r.branch_id);
    chosen.push(r);
  }
  const foundersOut = [];
  const branchesOut = [];
  for (const row of chosen) {
    if (isMinor(row)) throw new FactsError(`Refusing to write: "${row.first_name}" counts as a minor.`);
    if (!row.adult_confirmed) throw new FactsError(`Refusing to write: "${row.first_name}" is not a confirmed adult.`);
    if (row.hidden) throw new FactsError(`Refusing to write: "${row.first_name}" is hidden.`);
    const first = String(row.first_name || '').trim().split(/\s+/)[0];
    if (!first || first.length > 40 || /[^A-Za-z'’-]/.test(first)) throw new FactsError('Refusing to write: a first name is missing or not a single name.');
    const projected = { first, role: row.role };
    if (Object.keys(projected).join(',') !== 'first,role') throw new FactsError('Refusing to write: projected row has extra fields.');
    (row.role === 'founder' ? foundersOut : branchesOut).push(projected.first);
  }
  return { founders: foundersOut, branchParents: branchesOut };
}

export function renderPublicFactsModule(facts) {
  const body = {
    siteName: 'Team Lancaster',
    founders: facts.founders,
    branchParents: facts.branchParents,
    howTo: HOW_TO,
  };
  // Last line of defence: the JSON that ships contains names and the static how-to, nothing else.
  const json = JSON.stringify(body, null, 2);
  if (/"last_name"|"birth_year"|"id"|"email"|"bio/.test(json)) throw new FactsError('Refusing to write: rendered file would contain more than names.');
  return `// GENERATED by scripts/build-public-facts.js from D1 (public_ok = 1, confirmed adult, first names only).
// Do not edit the names by hand; they are replaced on the next build. The how-to text is static.
// This file is the ONLY thing the public guide and the public search read. Neither queries D1.
export const PUBLIC_FACTS = ${json};

export function factsAsText(f = PUBLIC_FACTS) {
  return [
    \`Site: \${f.siteName}.\`,
    \`Founders (first names): \${f.founders.join(', ')}.\`,
    \`Branch parents (first names): \${f.branchParents.join(', ')}.\`,
    ...f.howTo,
  ].join('\\n');
}
`;
}

const SQL = `SELECT role, first_name, adult_confirmed, public_ok, hidden, birth_year, death_year, is_deceased, branch_id, ord FROM (
  SELECT 'founder' AS role, first_name, adult_confirmed, public_ok, hidden, birth_year, death_year, is_deceased,
         NULL AS branch_id, 0 AS ord, birth_year AS sort_key, id AS sort_id
  FROM person WHERE is_founder = 1
  UNION ALL
  SELECT 'branch', p.first_name, p.adult_confirmed, p.public_ok, p.hidden, p.birth_year, p.death_year, p.is_deceased,
         b.id, CASE WHEN p.id = u.partner_a THEN 0 ELSE 1 END, b.sort, p.id
  FROM branch b JOIN unions u ON u.id = b.root_union_id
  JOIN person p ON p.id = u.partner_a OR p.id = u.partner_b
  WHERE p.is_founder = 0
) ORDER BY role DESC, sort_key, ord, sort_id`

function readD1(remote) {
  const args = ['wrangler', 'd1', 'execute', 'teamlancaster-family', remote ? '--remote' : '--local', '--json', '--command', SQL];
  const out = execFileSync('npx', args, { encoding: 'utf8' });
  const parsed = JSON.parse(out.slice(out.indexOf('[')));
  const set = parsed.find((x) => Array.isArray(x.results));
  if (!set) throw new FactsError('D1 returned no result set.');
  // Drop ordering columns before the projector sees the rows, so only check columns remain.
  return set.results.map((r) => Object.fromEntries(CHECK_COLUMNS.map((k) => [k, r[k] ?? null])));
}

function main() {
  const remote = process.argv.includes('--remote');
  const rows = readD1(remote);
  const facts = projectPublicFacts(rows); // throws before any write
  const file = new URL('../src/public-facts.js', import.meta.url);
  const tmp = new URL('../src/public-facts.js.tmp', import.meta.url);
  writeFileSync(tmp, renderPublicFactsModule(facts));
  renameSync(tmp, file);
  console.log(`Wrote src/public-facts.js from ${remote ? 'remote' : 'local'} D1: ${facts.founders.length} founders, ${facts.branchParents.length} branch parents.`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) main();
